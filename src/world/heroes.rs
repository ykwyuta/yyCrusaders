/// 英雄の肖像の数（絵の素材）
#[cfg_attr(not(test), allow(dead_code))]
pub const HERO_ART: usize = 46;

impl World {
    /// その国の英雄（ユニット番号）
    pub fn heroes_of(&self, n: usize) -> Vec<usize> {
        (0..self.units.len()).filter(|&i| self.units[i].alive && self.units[i].nation as usize == n && (self.units[i].hero as usize) < HEROES.len()).collect()
    }

    /// 遠征の始まりに英雄を置く
    pub(super) fn spawn_heroes(&mut self) {
        let s = self.scen;
        for (k, d) in HEROES.iter().enumerate() {
            if d.scen != s || !self.nations[d.nation].alive {
                continue;
            }
            let (x, y) = ll_to_tile(d.lon, d.lat);
            let p = self.passable_at_or_near(v2(x, y));
            let h = self.spawn_unit(d.nation, d.ut, p, d.power);
            self.unit_mut(h).unwrap().hero = k as u8;
        }
    }

    pub(super) fn passable_at_or_near(&self, p: V2) -> V2 {
        if self.passable_at(p) {
            p
        } else {
            let (cx, cy) = p.tile();
            for r in 1..14i32 {
                for dy in -r..=r {
                    for dx in -r..=r {
                        if dx.abs() != r && dy.abs() != r {
                            continue;
                        }
                        let q = v2((cx + dx) as f32 + 0.5, (cy + dy) as f32 + 0.5);
                        if self.passable_at(q) {
                            return q;
                        }
                    }
                }
            }
            p
        }
    }
}
