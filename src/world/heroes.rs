use super::*;

pub struct HeroDef {
    pub name: &'static str,
    /// 出身・生没年
    pub era: &'static str,
    /// 登場する遠征
    pub scen: Scen,
    /// 仕える国
    pub nation: usize,
    /// 始まりの居場所（経度・緯度）
    pub lon: f32,
    pub lat: f32,
    /// 兵種（UNIT_DEFS の番号）
    pub ut: u8,
    /// 能力
    pub power: f32,
    /// 肖像（絵の番号）
    pub art: u8,
    pub desc: &'static str,
}

